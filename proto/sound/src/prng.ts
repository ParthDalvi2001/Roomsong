// Mulberry32: tiny seeded PRNG so every procedural buffer (pluck excitation, reverb noise) is deterministic
// and unit-testable (CODING_GUIDELINES §9: no randomness without a seed).
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
